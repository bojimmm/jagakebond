"""Single source-file inventory for regression identity and immutable packaging."""
from pathlib import Path
import hashlib

SKIP = {'.git', '.env', 'data', 'node_modules', '__pycache__', '.gradle', 'build',
        'venv', '.venv', 'www', 'artifacts', 'outputs', '.idea', 'evidence-tools',
        'capacitor-cordova-android-plugins'}
PRIVATE_SUFFIXES = {'.pyc', '.db', '.sqlite', '.sqlite3', '.keystore', '.jks', '.apk',
                    '.aab', '.zip', '.gz', '.log'}


def source_files(root):
    root = Path(root)
    for group in ('app', 'android-client', 'review', 'tools', 'docs'):
        for path in sorted((root / group).rglob('*')):
            relative = path.relative_to(root)
            if not path.is_file() or path.is_symlink() or set(relative.parts) & SKIP:
                continue
            if group == 'docs' and path.suffix.lower() != '.md':
                continue  # Frozen verification records are not shipped as source.
            if (path.name == 'local.properties' or path.name.endswith('.tencent-mirror')
                    or path.suffix.lower() in PRIVATE_SUFFIXES):
                continue
            if path.name.startswith('.env') and path.name != '.env.example':
                continue
            if ('/src/main/assets/' in relative.as_posix() or
                    relative.as_posix() == 'android-client/android/app/src/main/res/xml/config.xml'):
                continue  # Generated by cap sync; verified inside APK instead.
            if group == 'review' and not (path.suffix in {'.py', '.cjs', '.mjs'} or
                                          path.name in {'package.json', 'package-lock.json'}):
                continue  # Never ship generated test output as source.
            yield relative.as_posix(), path
    for path in sorted(root.glob('*.md')):
        if not path.is_symlink():
            yield path.name, path


def source_hashes(root):
    return {name: hashlib.sha256(path.read_bytes()).hexdigest() for name, path in source_files(root)}
