"""Generate the browser's data-only problem registry from the backend vocabulary."""
from pathlib import Path
import json
import argparse
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Fail if the generated registry differs; do not write")
args = parser.parse_args()
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'app/reference/problem-vocabulary.json').read_text(encoding='utf-8'))
code='''/* Generated by tools/sync-problem-vocabulary.py. Edit the reference JSON. */
(function(root){
  'use strict';
  const data=__DATA__;
  const normalize=value=>String(value||'').trim().toLocaleLowerCase('id-ID').replace(/\\s+/g,' ').replace(/^(?:dugaan|diduga)\\s+/,'');
  function id(value){
    const text=normalize(value);
    const found=data.problems.find(p=>p.aliases.some(alias=>text===alias||text.startsWith(alias+' (')));
    return found?found.id:null;
  }
  function ids(record){
    let values;
    if(record.observedProblems&&typeof record.observedProblems==='object'){
      values=[record.observedProblems.disease,record.observedProblems.pest];
    }else{
      if(record.observedSeverity==='Healthy')return [];
      const report=record.assessment||{};
      if(report.uncertain||(record.needs_review&&typeof record.confidence==='number'&&record.confidence<.5)||String(record.severity||'').toLowerCase()==='healthy')return [];
      values=report.active_conditions&&report.active_conditions.length?report.active_conditions:[record.condition];
    }
    const result=[];
    for(const value of values){
      for(const part of String(value||'').split(/\\s*(?:\\+|·|;)\\s*/)){
        const key=id(part);if(key&&!result.includes(key))result.push(key);
      }
    }
    return result.slice(0,3);
  }
  const label=key=>(data.problems.find(p=>p.id===key)||{}).label||'Belum Dapat Dipastikan';
  const api={version:data.version,id,ids,label};
  root.JagaProblems=api;
  if(typeof module!=='undefined'&&module.exports)module.exports=api;
})(typeof window!=='undefined'?window:globalThis);
'''.replace('__DATA__',json.dumps(data,ensure_ascii=False,separators=(',',':')))
target = ROOT/'app/frontend/problem-registry.js'
if args.check:
    if target.read_text(encoding='utf-8') != code:
        raise SystemExit('Shared problem registry is stale')
    print('Shared problem registry matches.')
else:
    target.write_text(code,encoding='utf-8',newline='\n')
    print('Generated shared problem registry.')
